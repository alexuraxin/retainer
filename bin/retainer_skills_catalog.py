#!/usr/bin/env python3
"""Skills catalog from the frontmatter of live `SKILL.md` files.

`docs/SKILLS.md` is kept by hand, while the machine compared only the COUNT of skills with the
tree.
A rename or a change of purpose or scope never reached the catalog, and the document drifted from
the source unnoticed by any run: the count converges, the content lies.

The SECTION between markers is generated, not the whole document. The grouping by role and the
author text around it stay: a catalog of bare descriptions is worse for a human than the current
document, and the goal is to remove drift, not to impoverish the docs.

Descriptions are double-quoted, because a plain value carrying `: ` is not YAML and a strict
loader drops the skill; the catalog shows the text, not the quotes.

    retainer_skills_catalog.py [--check] [root]

Without a flag the section is rewritten. `--check` writes NOTHING to disk and fails on drift.
exit 0 -- matches (or written) · 1 -- drift · 3 -- no targets. Three, not two: the gate step
contract
separates "no targets" from "the check does not work", otherwise the summary goes green on a wrong
root.
"""

from __future__ import annotations

import json
import sys
from contextlib import suppress
from pathlib import Path

_BEGIN = "<!-- CATALOG: generated by retainer_skills_catalog.py, do not edit by hand -->"
_END = "<!-- END OF CATALOG -->"
_DOC = Path("docs/SKILLS.md")
_SKILLS = Path("skills")
_CARD = "SKILL.md"
_FENCE = "---"
_UTF8 = "utf-8"
_CHECK = "--check"
_NO_DESC = "description not read"
_CLEAN, _DIFFERS, _NOTHING = 0, 1, 3


def _field(line: str, fields: dict[str, str], key: str) -> str:
    """Add a frontmatter line to the fields; return the key the next line belongs to.

    An indented line is a continuation: descriptions may be multi-line, and joining them is the
    parser's job, not the skill author's. A one-line double-quoted value is decoded; one JSON
    cannot read, and any other value, stays as written.
    """
    if line[:1].isspace() and key:
        fields[key] = f"{fields[key]} {line.strip()}"
        return key
    parts = line.split(":", 1)
    if len(parts) < 2:
        return key
    name, text = (part.strip() for part in parts)
    if text.startswith('"'):
        with suppress(ValueError):
            text = json.loads(text)
    fields[name] = text
    return name


def _lines(path: Path) -> list[str]:
    """Frontmatter lines -- after the opening fence.

    An unreadable file and a foreign form give empty.
    """
    try:
        rows = path.read_text(encoding=_UTF8).splitlines()
    except OSError:
        return []
    return rows[1:] if rows[:1] == [_FENCE] else []


def _front(path: Path) -> tuple[str, str]:
    """(name, description) of a skill.

    If parsing fails: the directory name and an honest note instead of a description.

    Line-by-line parsing, no external YAML: a gate step has no right to a dependency the
    destination
    project may lack. Defaults are filled HERE, not at the caller: otherwise "no frontmatter" and
    "present but empty" would drift apart into two places.
    """
    fields: dict[str, str] = {}
    key = ""
    for line in _lines(path):
        if line.strip() == _FENCE:
            break
        key = _field(line, fields, key)
    name = fields.get("name") or path.parent.name
    return (name, fields.get("description") or _NO_DESC)


def _row(folder: Path) -> str:
    """Catalog line for one skill. Empty: no such skill in the catalog."""
    if not (folder / _CARD).is_file():
        return ""
    name, note = _front(folder / _CARD)
    return f"- **{name}** — {note}"


def _catalog(root: Path) -> str:
    """The whole catalog section -- one line per skill, in directory name order."""
    rows = [_row(folder) for folder in sorted((root / _SKILLS).iterdir())]
    listed = [row for row in rows if row]
    return "\n".join([_BEGIN, "", *listed, "", _END])


def _replace(text: str, body: str) -> str:
    """The document with the section rewritten. No markers: the section is appended at the end."""
    start = text.find(_BEGIN)
    stop = text.find(_END)
    if start < 0 or stop < 0:
        return f"{text.rstrip()}\n\n{body}\n"
    tail = text[stop + len(_END) :]
    return text[:start] + body + tail


def main() -> int:
    """Write the catalog section or (with `--check`) compare it, touching nothing."""
    named = [arg for arg in sys.argv[1:] if arg != _CHECK]
    root = Path(named[0] if named else ".").resolve()
    doc = root / _DOC
    if not (root / _SKILLS).is_dir() or not doc.is_file():
        sys.stdout.write("▶ skills catalog: no skills/ or docs/SKILLS.md -- nothing to check\n")
        return _NOTHING
    text = doc.read_text(encoding=_UTF8)
    want = _replace(text, _catalog(root))
    if want == text:
        sys.stdout.write("▶ skills catalog: matches the tree\n")
        return _CLEAN
    if _CHECK in sys.argv[1:]:
        sys.stderr.write(
            "✗ skills catalog diverged from the tree: a skill name or description was edited,"
            " the section was not rebuilt.\n"
            "  Fix: run retainer_skills_catalog.py and commit docs/SKILLS.md.\n"
        )
        return _DIFFERS
    doc.write_text(want, encoding=_UTF8)
    sys.stdout.write("✔ skills catalog rebuilt\n")
    return _CLEAN


if __name__ == "__main__":
    sys.exit(main())
